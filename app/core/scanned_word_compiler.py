def compile_scanned_word_edits(
    input_path: str | Path,
    output_pdf_path: str | Path,
    envelope: dict[str, Any],
    resolved_targets: list[dict[str, Any]],
    expected_source_sha256: str,
    cancellation_check: Callable[[], None] | None = None,
) -> dict[str, Any]:
    """Compile a complete trusted operation set or return a stable refusal.

    The resolved target rectangles are generated by the General Editor actor
    from its immutable extraction result; client-supplied coordinates are never
    accepted here. Refused requests leave the output path absent.
    """
    source_path = Path(input_path)
    output_path = Path(output_pdf_path)
    if source_path.resolve() == output_path.resolve():
        return _refusal("SOURCE_AND_OUTPUT_ARE_IDENTICAL")
    if output_path.exists():
        return _refusal("OUTPUT_ALREADY_EXISTS")
    if _sha256_file(source_path) != expected_source_sha256:
        return _refusal("SOURCE_BASELINE_MISMATCH")
    reason = _validate_transport(envelope, resolved_targets, expected_source_sha256)
    if reason:
        return _refusal(reason)

    if cancellation_check:
        cancellation_check()
    temporary = output_path.with_name(f".{output_path.name}.word-edit-tmp")
    temporary.unlink(missing_ok=True)
    try:
        with fitz.open(source_path) as source:
            if source.needs_pass:
                return _refusal("PROTECTED_SOURCE_UNSUPPORTED")
            page_count = len(source)
            if not page_count:
                return _refusal("INVALID_SOURCE_PDF")
            image_hashes = _image_hashes(source)
            geometry = [_page_geometry(page) for page in source]
            original_words = [_word_records(page) for page in source]
            plans: list[dict[str, Any]] = []
            for target in resolved_targets:
                if cancellation_check:
                    cancellation_check()
                plan, refusal = _prepare_target(source, target)
                if refusal:
                    return _refusal(refusal)
                plan["edit_order"] = len(plans)
                plans.append(plan)

            order_error = _assign_content_order(plans, source)
            if order_error:
                return _refusal(order_error)

            # Preflight the entire edit set before modifying any page.
            for index, left in enumerate(plans):
                for right in plans[index + 1:]:
                    if left["page_index"] == right["page_index"] and left["allowed_rect"].intersects(right["allowed_rect"]):
                        return _refusal("WORD_EDIT_TARGET_COLLISION")

        document = fitz.open(source_path)
        try:
            plans_by_page: dict[int, list[dict[str, Any]]] = {}
            for plan in plans:
                plans_by_page.setdefault(plan["page_index"], []).append(plan)
            for page_index, page_plans in plans_by_page.items():
                if cancellation_check:
                    cancellation_check()
                page = document[page_index]
                redactions = [plan["redaction_rect"] for plan in page_plans if plan["redaction_rect"] is not None]
                for redaction_rect in redactions:
                    page.add_redact_annot(redaction_rect, fill=None, cross_out=False)
                if redactions:
                    # PyMuPDF 1.28: images=0 and graphics=0 preserve all
                    # existing image and vector drawing content; text=0 removes
                    # only text whose glyph boxes intersect our preflighted
                    # rectangles.
                    page.apply_redactions(
                        images=fitz.PDF_REDACT_IMAGE_NONE,
                        graphics=fitz.PDF_REDACT_LINE_ART_NONE,
                        text=fitz.PDF_REDACT_TEXT_REMOVE,
                    )
                for plan in sorted(page_plans, key=lambda item: (item["insertion_slot"], item["edit_order"])):
                    if cancellation_check:
                        cancellation_check()
                    replacement = plan["edit"]["replacement_text"]
                    if plan["representation"] in {"image_scan", "searchable_scan"}:
                        page.insert_image(
                            plan["allowed_rect"],
                            stream=plan["patch_png"],
                            overlay=True,
                            keep_proportion=False,
                        )
                        if replacement:
                            plan["semantic_xref"] = _insert_semantic_text(
                                page,
                                plan["target_rect"].x0,
                                plan["baseline"],
                                replacement,
                                fontname=plan.get("semantic_fontname") or "tibo",
                                fontsize=plan["font_size"],
                                color=plan["ink_color"],
                                render_mode=3,
                                fontfile=plan.get("semantic_fontfile"),
                            )
                    elif replacement:
                        if plan.get("shaped_patch_png"):
                            page.insert_image(
                                plan["replacement_rect"],
                                stream=plan["shaped_patch_png"],
                                overlay=True,
                                keep_proportion=False,
                            )
                            render_mode = 3
                        else:
                            render_mode = 0
                        plan["semantic_xref"] = _insert_semantic_text(
                            page,
                            plan["text_origin"][0],
                            plan["text_origin"][1],
                            replacement,
                            fontname=plan.get("semantic_fontname") or plan["font_alias"],
                            fontsize=plan["font_size"],
                            color=plan["ink_color"],
                            render_mode=render_mode,
                            fontfile=plan.get("semantic_fontfile"),
                        )
                _reorder_semantic_streams(document, page, page_plans)
            document.save(temporary, garbage=0, deflate=False, deflate_images=False)
        finally:
            document.close()

        checks = _validate_candidate(
            source_path,
            temporary,
            plans,
            page_count,
            geometry,
            original_words,
            image_hashes,
            cancellation_check,
        )
        if not checks["valid"]:
            temporary.unlink(missing_ok=True)
            return _refusal("CANDIDATE_VALIDATION_FAILED", checks=checks)
        output_path.parent.mkdir(parents=True, exist_ok=True)
        os.replace(temporary, output_path)
        return {
            "status": "EDITED",
            "protocol": WORD_EDIT_PROTOCOL,
            "page_count": page_count,
            "operation_count": len(plans),
            "source_sha256": expected_source_sha256,
            "artifact_sha256": _sha256_file(output_path),
            "image_streams_preserved": True,
            "outside_changed_pixels_144dpi": checks["outside_changed_pixels_144dpi"],
            "outside_changed_pixels_by_dpi": checks["outside_changed_pixels_by_dpi"],
            "target_results": checks["target_results"],
        }
    except Exception as exc:
        temporary.unlink(missing_ok=True)
        # Keep internal parser detail out of public job errors.
        return _refusal("SCANNED_WORD_COMPILATION_FAILED", error_type=type(exc).__name__)


def _validate_transport(
    envelope: Any,
    resolved_targets: Any,
    expected_source_sha256: str,
) -> str | None:
    if type(envelope) is not dict or set(envelope) != {
        "edit_protocol", "source_tracker", "extraction_job_id", "baseline_digest", "edits"
    }:
        return "MALFORMED_WORD_EDIT_REQUEST"
    if envelope.get("edit_protocol") != WORD_EDIT_PROTOCOL:
        return "UNKNOWN_WORD_EDIT_PROTOCOL"
    edits = envelope.get("edits")
    if type(edits) is not list or not 1 <= len(edits) <= MAX_WORD_EDIT_OPERATIONS:
        return "MALFORMED_WORD_EDIT_REQUEST"
    if type(resolved_targets) is not list or len(resolved_targets) != len(edits):
        return "RESOLVED_TARGET_MISMATCH"
    if type(expected_source_sha256) is not str or len(expected_source_sha256) != 64:
        return "SOURCE_BASELINE_MISMATCH"
    for edit, target in zip(edits, resolved_targets, strict=True):
        if type(target) is not dict or set(target) != {"edit", "bbox", "page_size", "source_sha256", "baseline_digest"}:
            return "RESOLVED_TARGET_MISMATCH"
        if target["edit"] != edit or target["source_sha256"] != expected_source_sha256:
            return "RESOLVED_TARGET_MISMATCH"
        if target["baseline_digest"] != envelope["baseline_digest"]:
            return "RESOLVED_TARGET_MISMATCH"
        if type(target["bbox"]) is not list or len(target["bbox"]) != 4:
            return "UNSUPPORTED_WORD_GEOMETRY"
        if type(target["page_size"]) is not list or len(target["page_size"]) != 2:
            return "UNSUPPORTED_WORD_GEOMETRY"
        if any(type(value) not in (int, float) or not math.isfinite(value) for value in target["bbox"] + target["page_size"]):
            return "UNSUPPORTED_WORD_GEOMETRY"
        replacement = edit.get("replacement_text")
        if type(replacement) is not str:
            return "UNSUPPORTED_REPLACEMENT_TEXT"
        script_profile, script_error = _script_profile(replacement)
        if script_error:
            return script_error
        if script_profile is None and any(ord(char) > 0x7F for char in replacement):
            return "UNSUPPORTED_REPLACEMENT_TEXT"
        if script_profile is None and any(not (char.isalpha() or char.isdigit() or char in " -'.,;:!?()") for char in replacement):
            return "UNSUPPORTED_REPLACEMENT_TEXT"
    return None


def _prepare_target(source: fitz.Document, resolved: dict[str, Any]) -> tuple[dict[str, Any] | None, str | None]:
    edit = resolved["edit"]
    page_index = edit["page_num"] - 1
    if type(page_index) is not int or page_index < 0 or page_index >= len(source):
        return None, "UNSUPPORTED_WORD_GEOMETRY"
    page = source[page_index]
    if not _supported_geometry(page):
        return None, "UNSUPPORTED_PAGE_GEOMETRY"
    expected_size = resolved["page_size"]
    if abs(page.rect.width - float(expected_size[0])) > 0.05 or abs(page.rect.height - float(expected_size[1])) > 0.05:
        return None, "UNSUPPORTED_WORD_GEOMETRY"
    x0, y0, x1, y1 = map(float, resolved["bbox"])
    visible_rect = fitz.Rect(x0, y0, x1, y1)
    visible_page = fitz.Rect(0.0, 0.0, float(page.rect.width), float(page.rect.height))
    native_page = _native_page_rect(page)
    if visible_rect.is_empty or not visible_page.contains(visible_rect):
        return None, "UNSUPPORTED_WORD_GEOMETRY"
    target_rect = visible_rect * page.derotation_matrix
    target_rect.normalize()
    if (
        target_rect.is_empty
        or not native_page.contains(target_rect)
        or target_rect.width > native_page.width * 0.5
        or target_rect.height > native_page.height * 0.15
    ):
        return None, "UNSUPPORTED_WORD_GEOMETRY"
    image_occurrences = _image_occurrences(page)
    intersecting_images = [item for item in image_occurrences if item[0].intersects(target_rect)]
    if any(not _supported_image_transform(rect, matrix) for rect, matrix in intersecting_images):
        return None, "UNSUPPORTED_IMAGE_TRANSFORM"
    containing_images = [rect for rect, _ in intersecting_images if rect.contains(target_rect)]
    if any(not rect.contains(target_rect) for rect, _ in intersecting_images):
        return None, "AMBIGUOUS_TARGET_REPRESENTATION"
    if len(containing_images) > 1:
        return None, "AMBIGUOUS_TARGET_REPRESENTATION"
    if containing_images:
        if page.rotation != 0:
            return None, "UNSUPPORTED_PAGE_GEOMETRY"
        return _prepare_scan_target(page, resolved, page_index, target_rect)
    return _prepare_native_target(page, resolved, page_index, target_rect)


def _prepare_scan_target(
    page: fitz.Page,
    resolved: dict[str, Any],
    page_index: int,
    target_rect: fitz.Rect,
) -> tuple[dict[str, Any] | None, str | None]:
    edit = resolved["edit"]
    allowed_rect = fitz.Rect(
        target_rect.x0 - _TARGET_MARGIN,
        target_rect.y0 - _TARGET_MARGIN,
        target_rect.x1 + _TARGET_MARGIN,
        target_rect.y1 + _TARGET_MARGIN,
    ) & page.rect
    detect_rect = fitz.Rect(target_rect.x0 - _DETECT_MARGIN, target_rect.y0 - _DETECT_MARGIN,
                            target_rect.x1 + _DETECT_MARGIN, target_rect.y1 + _DETECT_MARGIN) & page.rect
    context_rect = fitz.Rect(target_rect.x0 - _CONTEXT_MARGIN, target_rect.y0 - _CONTEXT_MARGIN,
                             target_rect.x1 + _CONTEXT_MARGIN, target_rect.y1 + _CONTEXT_MARGIN) & page.rect
    if allowed_rect.is_empty:
        return None, "UNSUPPORTED_WORD_GEOMETRY"
    if _drawing_overlaps(page, detect_rect):
        return None, "BACKGROUND_RULE_OVERLAP"
    hidden_rect, source_word_index, hidden_error = _hidden_target_rect(page, target_rect, edit["expected_original_text"])
    if hidden_error:
        return None, hidden_error

    pix = page.get_pixmap(dpi=_PATCH_DPI, clip=context_rect, colorspace=fitz.csRGB, alpha=False)
    context = Image.frombytes("RGB", (pix.width, pix.height), pix.samples)
    scale = _PATCH_DPI / 72.0
    context_origin_x, context_origin_y = int(pix.x), int(pix.y)
    detect_px = _rect_pixels(detect_rect, scale, context.size, context_origin_x, context_origin_y)
    allowed_px = _rect_pixels(allowed_rect, scale, context.size, context_origin_x, context_origin_y)
    overlap = _detect_protected_overlap(context, detect_px)
    if overlap:
        return None, overlap
    try:
        repaired, ink_mask = _repair_ink_mask(context, allowed_px)
    except ValueError:
        return None, "BACKGROUND_UNCERTAIN"
    patch = repaired.crop(allowed_px)
    if patch.width < 2 or patch.height < 2:
        return None, "UNSUPPORTED_WORD_GEOMETRY"
    ink_color = _ink_color(context, ink_mask)
    replacement = edit["replacement_text"]
    font_size = target_rect.height * 1.10
    replacement_script, script_error = _script_profile(replacement)
    if script_error:
        return None, script_error
    semantic_fontfile = None
    semantic_fontname = "tibo"
    if replacement:
        baseline = target_rect.y0 + target_rect.height * 0.80
        if replacement_script is not None:
            # A searchable scan has a trusted OCR baseline and font size in its
            # hidden text span. Use those metrics to align the shaped visible
            # patch and the invisible Unicode replacement. Image-only scans do
            # not provide enough typography evidence to place complex scripts
            # safely, so refuse them instead of guessing from the OCR box.
            if hidden_rect is None or source_word_index is None:
                return None, "SCRIPT_SCAN_STYLE_UNRESOLVED"
            script_metrics = _hidden_word_metrics(page, source_word_index)
            if script_metrics is None:
                return None, "SCRIPT_SCAN_STYLE_UNRESOLVED"
            baseline, font_size = script_metrics
            script_font = _SCRIPT_FONTS[replacement_script]
            shaped, shape_error = _render_shaped_script_patch(
                replacement, script_font, font_size, target_rect.width * 0.96, ink_color
            )
            if shape_error:
                return None, shape_error
            if shaped is None:
                return None, "SCRIPT_SHAPING_UNSUPPORTED"
            rendered_rect = fitz.Rect(
                target_rect.x0 + shaped["offset_x"],
                baseline + shaped["offset_y"],
                target_rect.x0 + shaped["offset_x"] + shaped["width"],
                baseline + shaped["offset_y"] + shaped["height"],
            )
            if not target_rect.contains(rendered_rect):
                return None, "REPLACEMENT_DOES_NOT_FIT"
            patch_origin_x = (context_origin_x + allowed_px[0]) / scale
            patch_origin_y = (context_origin_y + allowed_px[1]) / scale
            local_x = round((rendered_rect.x0 - patch_origin_x) * scale)
            local_y = round((rendered_rect.y0 - patch_origin_y) * scale)
            overlay = Image.open(BytesIO(shaped["png"])).convert("RGBA")
            if local_x < 0 or local_y < 0 or local_x + overlay.width > patch.width or local_y + overlay.height > patch.height:
                return None, "REPLACEMENT_DOES_NOT_FIT"
            composite = Image.new("RGBA", patch.size, (0, 0, 0, 0))
            composite.alpha_composite(overlay, (local_x, local_y))
            patch = Image.alpha_composite(patch.convert("RGBA"), composite).convert("RGB")
            semantic_fontfile = script_font["fontfile"]
            semantic_fontname = script_font["fontname"]
        else:
            measured_width = fitz.get_text_length(replacement, fontname="tibo", fontsize=font_size)
            if measured_width > target_rect.width * 0.96:
                return None, "REPLACEMENT_DOES_NOT_FIT"
            try:
                patch = _render_replacement_patch(
                    patch,
                    allowed_px,
                    context_origin_x,
                    context_origin_y,
                    target_rect,
                    baseline,
                    replacement,
                    font_size,
                    ink_color,
                )
            except Exception:
                return None, "REPLACEMENT_RENDER_UNSUPPORTED"
    insertion_slot = source_word_index
    if insertion_slot is None:
        insertion_slot, order_error = _scan_insertion_slot(page, target_rect)
        if order_error:
            return None, order_error
    return {
        "edit": edit,
        "page_index": page_index,
        "target_rect": target_rect,
        "allowed_rect": allowed_rect,
        "replacement_rect": target_rect,
        "redaction_rect": hidden_rect,
        "representation": "searchable_scan" if hidden_rect is not None else "image_scan",
        "source_word_index": source_word_index,
        "insertion_slot": insertion_slot,
        "baseline": target_rect.y0 + target_rect.height * 0.80,
        "font_size": font_size,
        "ink_color": ink_color,
        "patch_png": _png_bytes(patch),
        "semantic_fontfile": semantic_fontfile,
        "semantic_fontname": semantic_fontname,
    }, None


def _prepare_native_target(
    page: fitz.Page,
    resolved: dict[str, Any],
    page_index: int,
    requested_rect: fitz.Rect,
) -> tuple[dict[str, Any] | None, str | None]:
    edit = resolved["edit"]
    expected = edit["expected_original_text"]
    if any(0xFB00 <= ord(char) <= 0xFB06 for char in expected):
        return None, "NATIVE_GLYPH_CLUSTER_UNSUPPORTED"
    expected_script, expected_script_error = _script_profile(expected)
    if not expected or expected_script_error or (any(ord(char) > 0x7F for char in expected) and expected_script is None):
        return None, "NATIVE_SOURCE_TEXT_UNSUPPORTED"
    words = page.get_text("words", sort=False)
    matching_words: list[tuple[int, Any, fitz.Rect]] = []
    for index, word in enumerate(words):
        if str(word[4]) != expected:
            continue
        word_rect = fitz.Rect(word[:4])
        intersection = word_rect & requested_rect
        denominator = min(word_rect.get_area(), requested_rect.get_area())
        if not intersection.is_empty and intersection.get_area() / max(0.01, denominator) >= 0.65:
            matching_words.append((index, word, word_rect))
    if not matching_words:
        return None, "NATIVE_TARGET_NOT_FOUND"
    if len(matching_words) != 1:
        return None, "NATIVE_TARGET_AMBIGUOUS"
    source_word_index, source_word, word_rect = matching_words[0]
    traces = page.get_texttrace()
    selected_chars: list[tuple[int, int, dict[str, Any], Any, fitz.Rect]] = []
    for span_index, span in enumerate(traces):
        for char_index, char in enumerate(span.get("chars", ())):
            if len(char) < 4:
                continue
            glyph_rect = fitz.Rect(char[3])
            center = fitz.Point((glyph_rect.x0 + glyph_rect.x1) / 2, (glyph_rect.y0 + glyph_rect.y1) / 2)
            if word_rect.contains(center):
                selected_chars.append((span_index, char_index, span, char, glyph_rect))
    span_indices = {entry[0] for entry in selected_chars if int(entry[3][0]) != 32}
    if not selected_chars or not span_indices:
        return None, "NATIVE_SOURCE_GLYPHS_UNRESOLVED"
    if len(span_indices) != 1:
        return None, "NATIVE_STYLE_SPANS_UNSUPPORTED"
    span_index = next(iter(span_indices))
    span = traces[span_index]
    glyph_chars = [entry for entry in selected_chars if entry[0] == span_index and int(entry[3][0]) != 32]
    source_text = "".join(chr(int(entry[3][0])) for entry in glyph_chars)
    source_script, source_script_error = _script_profile(source_text)
    if source_script_error or (any(ord(char) > 0x7F for char in source_text) and source_script is None):
        return None, "NATIVE_GLYPH_CLUSTER_UNSUPPORTED"
    if source_text != expected:
        return None, "NATIVE_SOURCE_TEXT_IDENTITY_MISMATCH"
    if span.get("type") != 0 or span.get("wmode") != 0 or tuple(span.get("dir", ())) != (1.0, 0.0):
        return None, "NATIVE_TEXT_RENDERING_UNSUPPORTED"
    replacement = edit["replacement_text"]
    replacement_script, script_error = _script_profile(replacement)
    if script_error:
        return None, script_error
    font_name = str(span.get("font", ""))
    font_alias = _NATIVE_FONT_ALIASES.get(font_name)
    if replacement and font_alias is None and replacement_script is None:
        return None, "NATIVE_FONT_UNSUPPORTED"
    if replacement_script is not None:
        script_font = _SCRIPT_FONTS[replacement_script]
        fontfile = Path(script_font["fontfile"])
        if not fontfile.is_file():
            return None, "SCRIPT_FONT_UNAVAILABLE"
        try:
            font = fitz.Font(fontfile=str(fontfile))
        except Exception:
            return None, "SCRIPT_FONT_UNAVAILABLE"
    else:
        script_font = None
        fontfile = None
        try:
            font = fitz.Font(fontname=font_alias) if font_alias is not None else None
        except Exception:
            return None, "NATIVE_FONT_UNSUPPORTED"
    fontsize = float(span.get("size", 0.0))
    if not math.isfinite(fontsize) or fontsize <= 0:
        return None, "NATIVE_FONT_UNSUPPORTED"
    origin = tuple(map(float, glyph_chars[0][3][2]))
    color = _normalize_color(span.get("color", (0.0, 0.0, 0.0)))
    glyph_rects = [entry[4] for entry in glyph_chars]
    redaction_rect = _union_rects(glyph_rects)
    selected_ids = {(entry[0], entry[1]) for entry in glyph_chars}
    for other_span_index, other_span in enumerate(traces):
        for other_index, char in enumerate(other_span.get("chars", ())):
            if len(char) < 4 or (other_span_index, other_index) in selected_ids or int(char[0]) == 32:
                continue
            other_rect = fitz.Rect(char[3])
            if _overlap_area(other_rect, redaction_rect) > 0.05:
                return None, "NATIVE_GLYPH_OVERLAP"

    replacement_extent = None
    shaped_patch_png = None
    if replacement:
        if not replacement.strip():
            return None, "UNSUPPORTED_REPLACEMENT_TEXT"
        if not _font_covers_text(font, replacement):
            return None, "NATIVE_FONT_GLYPH_UNSUPPORTED"
        same_line_neighbors: list[fitz.Rect] = []
        for other_span_index, other_span in enumerate(traces):
            for other_index, char in enumerate(other_span.get("chars", ())):
                if len(char) < 4 or (other_span_index, other_index) in selected_ids or int(char[0]) == 32:
                    continue
                other_origin = char[2]
                other_rect = fitz.Rect(char[3])
                if abs(float(other_origin[1]) - origin[1]) <= fontsize * 0.30:
                    same_line_neighbors.append(other_rect)
        next_glyph_x = min(
            (rect.x0 for rect in same_line_neighbors if rect.x0 >= word_rect.x1 - 0.05),
            default=_native_page_rect(page).x1,
        )
        if replacement_script is not None:
            shaped, shape_error = _render_shaped_script_patch(
                replacement,
                script_font,
                fontsize,
                max(0.0, next_glyph_x - origin[0] - 0.35),
                color,
            )
            if shape_error:
                return None, shape_error
            shaped_patch_png = shaped["png"]
            replacement_extent = fitz.Rect(
                origin[0] + shaped["offset_x"],
                origin[1] + shaped["offset_y"],
                origin[0] + shaped["offset_x"] + shaped["width"],
                origin[1] + shaped["offset_y"] + shaped["height"],
            )
        else:
            projected_glyphs = _project_font_glyphs(font, replacement, origin, fontsize)
            if not projected_glyphs:
                return None, "UNSUPPORTED_REPLACEMENT_TEXT"
            replacement_extent = _union_rects(projected_glyphs)
            text_width = font.text_length(replacement, fontsize)
            if origin[0] + text_width > next_glyph_x - 0.35:
                return None, "REPLACEMENT_DOES_NOT_FIT"
            if any(_overlap_area(projected, neighbor) > 0.05 for projected in projected_glyphs for neighbor in same_line_neighbors):
                return None, "NATIVE_REPLACEMENT_COLLISION"
        native_bounds = _native_page_rect(page)
        if replacement_extent.x0 < native_bounds.x0 or replacement_extent.y0 < native_bounds.y0 or replacement_extent.x1 > native_bounds.x1 or replacement_extent.y1 > native_bounds.y1:
            return None, "UNSUPPORTED_WORD_GEOMETRY"
    allowed_rect = fitz.Rect(word_rect)
    if replacement_extent is not None:
        allowed_rect |= replacement_extent
    if any(rect.intersects(allowed_rect) for rect in _image_rects(page)):
        return None, "NATIVE_IMAGE_OVERLAP"
    if _drawing_overlaps(page, allowed_rect):
        return None, "NATIVE_GRAPHICS_OVERLAP"
    if _annotation_overlaps(page, allowed_rect):
        return None, "NATIVE_ANNOTATION_OVERLAP"

    return {
        "edit": edit,
        "page_index": page_index,
        "target_rect": word_rect,
        "allowed_rect": allowed_rect,
        "replacement_rect": replacement_extent or word_rect,
        "redaction_rect": redaction_rect,
        "representation": "native_text",
        "source_word_index": source_word_index,
        "insertion_slot": source_word_index,
        "text_origin": origin,
        "font_alias": font_alias,
        "semantic_fontfile": str(fontfile) if fontfile is not None else None,
        "semantic_fontname": script_font["fontname"] if script_font is not None else font_alias,
        "shaped_patch_png": shaped_patch_png,
        "font_size": fontsize,
        "ink_color": color,
    }, None


def _image_rects(page: fitz.Page) -> list[fitz.Rect]:
    return [rect for rect, _ in _image_occurrences(page)]


def _image_occurrences(page: fitz.Page) -> list[tuple[fitz.Rect, fitz.Matrix]]:
    occurrences: list[tuple[fitz.Rect, fitz.Matrix]] = []
    for image in page.get_images(full=True):
        xref = int(image[0])
        if xref > 0:
            try:
                placements = page.get_image_rects(xref, transform=True)
            except (AttributeError, RuntimeError, ValueError):
                placements = [
                    (rect, fitz.Matrix(float("nan"), 0, 0, float("nan"), 0, 0))
                    for rect in page.get_image_rects(xref)
                ]
            for rect, matrix in placements:
                occurrences.append((fitz.Rect(rect), fitz.Matrix(matrix)))
    return occurrences


def _supported_image_transform(rect: fitz.Rect, matrix: fitz.Matrix) -> bool:
    """Accept only positive axis-aligned image scaling plus translation."""
    values = tuple(float(value) for value in matrix)
    if len(values) != 6 or any(not math.isfinite(value) for value in values):
        return False
    a, b, c, d, _, _ = values
    if a <= 0 or d <= 0 or abs(b) > 1e-5 or abs(c) > 1e-5:
        return False
    mapped_unit = fitz.Rect(0, 0, 1, 1) * matrix
    return (
        abs(mapped_unit.x0 - rect.x0) < 0.05
        and abs(mapped_unit.y0 - rect.y0) < 0.05
        and abs(mapped_unit.x1 - rect.x1) < 0.05
        and abs(mapped_unit.y1 - rect.y1) < 0.05
    )


def _union_rects(rectangles: list[fitz.Rect]) -> fitz.Rect:
    if not rectangles:
        return fitz.Rect()
    return fitz.Rect(
        min(rect.x0 for rect in rectangles),
        min(rect.y0 for rect in rectangles),
        max(rect.x1 for rect in rectangles),
        max(rect.y1 for rect in rectangles),
    )


def _script_profile(text: str) -> tuple[str | None, str | None]:
    if not isinstance(text, str):
        return None, "UNSUPPORTED_REPLACEMENT_TEXT"
    present = [
        name for name, profile in _SCRIPT_FONTS.items()
        if any(profile["range"][0] <= ord(char) <= profile["range"][1] for char in text)
    ]
    if not present:
        if any(ord(char) > 0x7F for char in text):
            return None, "UNSUPPORTED_REPLACEMENT_TEXT"
        return None, None
    if len(present) != 1:
        return None, "UNSUPPORTED_REPLACEMENT_TEXT"
    selected = present[0]
    low, high = _SCRIPT_FONTS[selected]["range"]
    if not any(low <= ord(char) <= high and unicodedata.category(char).startswith("L") for char in text):
        return None, "UNSUPPORTED_REPLACEMENT_TEXT"
    for char in text:
        codepoint = ord(char)
        if low <= codepoint <= high or codepoint in (0x200C, 0x200D):
            continue
        if char.isascii() and (char.isalnum() or char.isspace() or char in "-'.,;:!?()"):
            continue
        return None, "UNSUPPORTED_REPLACEMENT_TEXT"
    return selected, None


def _font_covers_text(font: fitz.Font, text: str) -> bool:
    return all(
        ord(char) in (0x200C, 0x200D) or font.has_glyph(ord(char)) > 0
        for char in text
    )


def _render_shaped_script_patch(
    text: str,
    profile: dict[str, Any],
    fontsize: float,
    max_width: float,
    color: tuple[float, float, float],
) -> tuple[dict[str, Any] | None, str | None]:
    font_path = Path(profile["fontfile"])
    if not font_path.is_file():
        return None, "SCRIPT_FONT_UNAVAILABLE"
    if not math.isfinite(fontsize) or not 1.0 <= fontsize <= 256.0:
        return None, "SCRIPT_FONT_SIZE_UNSUPPORTED"
    if not math.isfinite(max_width) or max_width < 2.0 or max_width > 4096.0:
        return None, "REPLACEMENT_DOES_NOT_FIT"
    try:
        font = fitz.Font(fontfile=str(font_path))
    except Exception:
        return None, "SCRIPT_FONT_UNAVAILABLE"
    if not _font_covers_text(font, text):
        return None, "NATIVE_FONT_GLYPH_UNSUPPORTED"

    scale = _PATCH_DPI / 72.0
    margin = max(12.0, fontsize * 1.5)
    width = max_width + 2 * margin
    height = fontsize * 4.0 + 2 * margin
    if math.ceil(width * scale) * math.ceil(height * scale) > _MAX_SCRIPT_PATCH_PIXELS:
        return None, "SCRIPT_PATCH_EXCEEDS_LIMIT"
    color_css = ",".join(str(round(max(0.0, min(1.0, channel)) * 255)) for channel in color)
    css = (
        f"@font-face{{font-family:{profile['family']};src:url({font_path.name});}}"
        "html,body{margin:0;padding:0;}"
        f"span{{font-family:{profile['family']};font-size:{fontsize:.4f}pt;"
        f"line-height:1.25;color:rgb({color_css});white-space:nowrap;}}"
    )
    document = fitz.open()
    try:
        page = document.new_page(width=width, height=height)
        text_rect = fitz.Rect(margin, margin, margin + max_width, height - margin)
        try:
            spare_height, layout_scale = page.insert_htmlbox(
                text_rect,
                f"<span>{html.escape(text, quote=False)}</span>",
                css=css,
                archive=fitz.Archive(str(font_path.parent)),
                scale_low=1.0,
            )
        except Exception:
            return None, "SCRIPT_SHAPING_UNSUPPORTED"
        if spare_height < 0 or layout_scale < 0.999999:
            return None, "REPLACEMENT_DOES_NOT_FIT"
        traces = [span for span in page.get_texttrace() if span.get("chars")]
        if not traces or any(
            span.get("type") != 0
            or span.get("wmode") != 0
            or tuple(span.get("dir", ())) != (1.0, 0.0)
            for span in traces
        ):
            return None, "SCRIPT_SHAPING_UNSUPPORTED"
        origins = [tuple(map(float, char[2])) for span in traces for char in span.get("chars", ()) if len(char) >= 3]
        if not origins or any(abs(origin[1] - origins[0][1]) > 0.1 for origin in origins):
            return None, "SCRIPT_SHAPING_UNSUPPORTED"

        pixmap = page.get_pixmap(matrix=fitz.Matrix(scale, scale), colorspace=fitz.csRGB, alpha=True)
        if pixmap.width * pixmap.height > _MAX_SCRIPT_PATCH_PIXELS or pixmap.n != 4:
            return None, "SCRIPT_PATCH_EXCEEDS_LIMIT"
        rendered = Image.frombytes("RGBA", (pixmap.width, pixmap.height), pixmap.samples)
        ink_bbox = rendered.getchannel("A").getbbox()
        if ink_bbox is None:
            return None, "SCRIPT_SHAPING_UNSUPPORTED"
        shaped = rendered.crop(ink_bbox)
        baseline_x, baseline_y = origins[0]
        offset_x = float(pixmap.x) / scale + ink_bbox[0] / scale - baseline_x
        offset_y = float(pixmap.y) / scale + ink_bbox[1] / scale - baseline_y
        return {
            "png": _png_bytes(shaped),
            "width": shaped.width / scale,
            "height": shaped.height / scale,
            "offset_x": offset_x,
            "offset_y": offset_y,
        }, None
    finally:
        document.close()


def _native_page_rect(page: fitz.Page) -> fitz.Rect:
    """Return the unrotated CropBox-relative frame used by text/page APIs."""
    return fitz.Rect(0.0, 0.0, float(page.cropbox.width), float(page.cropbox.height))


def _overlap_area(left: fitz.Rect, right: fitz.Rect) -> float:
    intersection = left & right
    return 0.0 if intersection.is_empty else intersection.get_area()


def _normalize_color(value: Any) -> tuple[float, float, float]:
    if type(value) in (int, float):
        channel = max(0.0, min(1.0, float(value)))
        return channel, channel, channel
    if isinstance(value, (tuple, list)) and len(value) >= 3:
        return tuple(max(0.0, min(1.0, float(channel))) for channel in value[:3])
    return 0.0, 0.0, 0.0


def _project_font_glyphs(font: fitz.Font, text: str, origin: tuple[float, float], fontsize: float) -> list[fitz.Rect]:
    cursor_x = origin[0]
    rectangles: list[fitz.Rect] = []
    for char in text:
        codepoint = ord(char)
        glyph = font.glyph_bbox(codepoint)
        if not glyph.is_empty:
            rectangles.append(fitz.Rect(
                cursor_x + glyph.x0 * fontsize,
                origin[1] - glyph.y1 * fontsize,
                cursor_x + glyph.x1 * fontsize,
                origin[1] - glyph.y0 * fontsize,
            ))
        cursor_x += font.glyph_advance(codepoint) * fontsize
    return rectangles


def _annotation_overlaps(page: fitz.Page, target: fitz.Rect) -> bool:
    annotations = list(page.annots() or ())
    widgets = list(page.widgets() or ())
    return any(fitz.Rect(item.rect).intersects(target) for item in annotations + widgets)


def _render_replacement_patch(
    patch: Image.Image,
    allowed_px: tuple[int, int, int, int],
    context_origin_x: int,
    context_origin_y: int,
    target_rect: fitz.Rect,
    baseline: float,
    replacement: str,
    font_size: float,
    color: tuple[float, float, float],
) -> Image.Image:
    scale = _PATCH_DPI / 72.0
    patch_origin_x = (context_origin_x + allowed_px[0]) / scale
    patch_origin_y = (context_origin_y + allowed_px[1]) / scale
    overlay_doc = fitz.open()
    try:
        page = overlay_doc.new_page(width=patch.width / scale, height=patch.height / scale)
        page.insert_text(
            fitz.Point(target_rect.x0 - patch_origin_x, baseline - patch_origin_y),
            replacement,
            fontname="tibo",
            fontsize=font_size,
            color=color,
            overlay=True,
        )
        pixmap = page.get_pixmap(matrix=fitz.Matrix(scale, scale), colorspace=fitz.csRGB, alpha=True)
        overlay = Image.frombytes("RGBA", (pixmap.width, pixmap.height), pixmap.samples)
        if overlay.size != patch.size:
            aligned = Image.new("RGBA", patch.size, (0, 0, 0, 0))
            aligned.alpha_composite(overlay.crop((0, 0, min(overlay.width, patch.width), min(overlay.height, patch.height))))
            overlay = aligned
        return Image.alpha_composite(patch.convert("RGBA"), overlay).convert("RGB")
    finally:
        overlay_doc.close()


def _scan_insertion_slot(page: fitz.Page, target_rect: fitz.Rect) -> tuple[int | None, str | None]:
    words = page.get_text("words", sort=False)
    if not words:
        return 0, None
    first, last = fitz.Rect(words[0][:4]), fitz.Rect(words[-1][:4])
    if target_rect.y1 <= first.y0 or (abs(target_rect.y0 - first.y0) < 0.5 and target_rect.x1 <= first.x0):
        return 0, None
    if target_rect.y0 >= last.y1 or (abs(target_rect.y0 - last.y0) < 0.5 and target_rect.x0 >= last.x1):
        return len(words), None
    return None, "TEXT_READING_ORDER_UNSUPPORTED"


def _assign_content_order(plans: list[dict[str, Any]], source: fitz.Document) -> str | None:
    by_page: dict[int, list[dict[str, Any]]] = {}
    for plan in plans:
        by_page.setdefault(plan["page_index"], []).append(plan)
    for page_index, page_plans in by_page.items():
        source_words = source[page_index].get_text("words", sort=False)
        targeted_indices = {
            plan["source_word_index"]
            for plan in page_plans
            if plan["source_word_index"] is not None
        }
        for plan in page_plans:
            slot = plan["insertion_slot"]
            prefix = all(index in targeted_indices for index in range(slot))
            suffix = all(index in targeted_indices for index in range(slot, len(source_words)))
            if prefix:
                plan["semantic_position"] = "head"
            elif suffix:
                plan["semantic_position"] = "tail"
            elif plan["edit"]["replacement_text"]:
                return "TEXT_READING_ORDER_UNSUPPORTED"
            else:
                # A deletion adds no text object, so the existing stream order
                # remains correct regardless of its position.
                plan["semantic_position"] = "tail"
    return None


def _insert_semantic_text(
    page: fitz.Page,
    x: float,
    y: float,
    text: str,
    *,
    fontname: str,
    fontsize: float,
    color: tuple[float, float, float],
    render_mode: int,
    fontfile: str | None = None,
) -> int:
    if fontfile:
        page.insert_font(fontname=fontname, fontfile=fontfile)
    before = set(page.get_contents())
    page.insert_text(
        fitz.Point(x, y),
        text,
        fontname=fontname,
        fontsize=fontsize,
        color=color,
        render_mode=render_mode,
        overlay=True,
    )
    created = [xref for xref in page.get_contents() if xref not in before]
    if len(created) != 1:
        raise RuntimeError("native text insertion did not create one isolated content stream")
    return created[0]


def _reorder_semantic_streams(document: fitz.Document, page: fitz.Page, plans: list[dict[str, Any]]) -> None:
    head = [
        plan["semantic_xref"]
        for plan in sorted(plans, key=lambda item: (item["insertion_slot"], item["edit_order"]))
        if plan.get("semantic_position") == "head" and plan.get("semantic_xref")
    ]
    tail = [
        plan["semantic_xref"]
        for plan in sorted(plans, key=lambda item: (item["insertion_slot"], item["edit_order"]))
        if plan.get("semantic_position") == "tail" and plan.get("semantic_xref")
    ]
    semantic = set(head + tail)
    base = [xref for xref in page.get_contents() if xref not in semantic]
    ordered = head + base + tail
    if len(ordered) != len(set(ordered)):
        raise RuntimeError("duplicate page content stream identity")
    document.xref_set_key(page.xref, "Contents", "[" + " ".join(f"{xref} 0 R" for xref in ordered) + "]")


def _supported_geometry(page: fitz.Page) -> bool:
    rotation = page.rotation
    if rotation not in (0, 90, 180, 270):
        return False
    crop = page.cropbox
    media = page.mediabox
    if crop.is_empty or crop.width <= 0 or crop.height <= 0 or media.is_empty:
        return False
    expected_size = (crop.height, crop.width) if rotation in (90, 270) else (crop.width, crop.height)
    return (
        abs(page.rect.x0) < 0.05
        and abs(page.rect.y0) < 0.05
        and abs(page.rect.width - expected_size[0]) < 0.05
        and abs(page.rect.height - expected_size[1]) < 0.05
    )


def _image_contains_target(page: fitz.Page, target: fitz.Rect) -> bool:
    containing: list[fitz.Rect] = []
    for image in page.get_images(full=True):
        xref = int(image[0])
        if xref <= 0:
            continue
        for rect in page.get_image_rects(xref):
            if rect.contains(target):
                containing.append(rect)
    return len(containing) == 1


def _drawing_overlaps(page: fitz.Page, target: fitz.Rect) -> bool:
    for drawing in page.get_drawings():
        rect = fitz.Rect(drawing.get("rect", (0, 0, 0, 0)))
        if not rect.is_empty and rect.intersects(target):
            return True
        for item in drawing.get("items", ()):
            if not item:
                continue
            if item[0] == "l" and len(item) >= 3:
                line = fitz.Rect(item[1], item[2])
                line.x0 -= 0.3
                line.y0 -= 0.3
                line.x1 += 0.3
                line.y1 += 0.3
                if line.intersects(target):
                    return True
    return False


def _normalize_text(value: str) -> str:
    return value.strip().strip(".,;:!?\"'()[]{}<>–—").casefold()


def _hidden_target_rect(
    page: fitz.Page,
    target_rect: fitz.Rect,
    expected: str,
) -> tuple[fitz.Rect | None, int | None, str | None]:
    overlapping: list[tuple[int, fitz.Rect]] = []
    words = page.get_text("words", sort=False)
    for word_index, word in enumerate(words):
        if _normalize_text(str(word[4])) == _normalize_text(expected):
            rect = fitz.Rect(word[:4])
            if rect.intersects(target_rect):
                overlapping.append((word_index, rect))
    if not overlapping:
        # Any text at the image target is conflicting when it does not match
        # the frozen selected word, whether visible or hidden.
        if any(_trace_has_glyph_in_rect(span, target_rect) for span in page.get_texttrace()):
            return None, None, "TEXT_LAYER_CONFLICT"
        return None, None, None
    if len(overlapping) != 1:
        return None, None, "HIDDEN_OCR_AMBIGUOUS"
    word_index, text_rect = overlapping[0]
    intersection = text_rect & target_rect
    if intersection.is_empty or intersection.get_area() / max(0.01, min(text_rect.get_area(), target_rect.get_area())) < 0.65:
        return None, None, "HIDDEN_OCR_ALIGNMENT_UNCERTAIN"
    matching_spans: list[tuple[dict[str, Any], str, list[fitz.Rect]]] = []
    conflicting_glyph = False
    for span in page.get_texttrace():
        selected: list[tuple[int, fitz.Rect]] = []
        for char in span.get("chars", ()):
            if len(char) < 4:
                continue
            glyph_rect = fitz.Rect(char[3])
            center = fitz.Point((glyph_rect.x0 + glyph_rect.x1) / 2, (glyph_rect.y0 + glyph_rect.y1) / 2)
            if text_rect.contains(center) and int(char[0]) != 32:
                selected.append((int(char[0]), glyph_rect))
            elif _overlap_area(glyph_rect, text_rect) > 0.05 and int(char[0]) != 32:
                conflicting_glyph = True
        if selected:
            matching_spans.append((
                span,
                "".join(chr(codepoint) for codepoint, _ in selected),
                [rect for _, rect in selected],
            ))
    if conflicting_glyph or len(matching_spans) != 1:
        return None, None, "HIDDEN_OCR_AMBIGUOUS"
    trace, selected_text, selected_rects = matching_spans[0]
    if trace.get("type") != 3:
        return None, None, "VISIBLE_TEXT_LAYER_CONFLICT"
    if trace.get("wmode") != 0 or tuple(trace.get("dir", ())) != (1.0, 0.0):
        return None, None, "HIDDEN_OCR_ALIGNMENT_UNCERTAIN"
    if _normalize_text(selected_text) != _normalize_text(expected):
        return None, None, "HIDDEN_OCR_ALIGNMENT_UNCERTAIN"
    redact = fitz.Rect(text_rect.x0 - 0.1, text_rect.y0 - 0.1, text_rect.x1 + 0.1, text_rect.y1 + 0.1)
    # OCR/native text boxes can differ from the rendered ink by a fraction of
    # a point. Keep hidden-layer removal tightly bounded to a 1.25pt margin.
    allowed = fitz.Rect(target_rect.x0 - 1.25, target_rect.y0 - 1.25,
                        target_rect.x1 + 1.25, target_rect.y1 + 1.25)
    if not allowed.contains(redact):
        return None, None, "HIDDEN_OCR_ALIGNMENT_UNCERTAIN"
    for other_index, word in enumerate(words):
        if other_index == word_index:
            continue
        if _overlap_area(fitz.Rect(word[:4]), redact) > 0.05:
            return None, None, "HIDDEN_OCR_NEIGHBOR_OVERLAP"
    selected_union = _union_rects(selected_rects)
    if not redact.contains(selected_union):
        return None, None, "HIDDEN_OCR_ALIGNMENT_UNCERTAIN"
    return redact, word_index, None


def _hidden_word_metrics(page: fitz.Page, word_index: int) -> tuple[float, float] | None:
    """Return the validated hidden OCR word's baseline and point size."""
    words = page.get_text("words", sort=False)
    if word_index < 0 or word_index >= len(words):
        return None
    word_rect = fitz.Rect(words[word_index][:4])
    matches: list[tuple[float, float]] = []
    for span in page.get_texttrace():
        selected = []
        for char in span.get("chars", ()):
            if len(char) < 4 or int(char[0]) == 32:
                continue
            glyph_rect = fitz.Rect(char[3])
            center = fitz.Point((glyph_rect.x0 + glyph_rect.x1) / 2, (glyph_rect.y0 + glyph_rect.y1) / 2)
            if word_rect.contains(center):
                selected.append(char)
        if selected:
            if span.get("type") != 3 or span.get("wmode") != 0 or tuple(span.get("dir", ())) != (1.0, 0.0):
                return None
            try:
                baseline = float(selected[0][2][1])
                fontsize = float(span["size"])
            except (IndexError, KeyError, TypeError, ValueError):
                return None
            if not math.isfinite(baseline) or not math.isfinite(fontsize) or fontsize <= 0:
                return None
            matches.append((baseline, fontsize))
    if len(matches) != 1:
        return None
    return matches[0]


def _trace_has_glyph_in_rect(span: dict[str, Any], target: fitz.Rect) -> bool:
    for char in span.get("chars", ()):
        if len(char) < 4:
            continue
        if _overlap_area(fitz.Rect(char[3]), target) > 0.05 and int(char[0]) != 32:
            return True
    return False


def _rect_pixels(rect: fitz.Rect, scale: float, size: tuple[int, int], origin_x: int, origin_y: int) -> tuple[int, int, int, int]:
    return (
        max(0, math.floor(rect.x0 * scale) - origin_x),
        max(0, math.floor(rect.y0 * scale) - origin_y),
        min(size[0], math.ceil(rect.x1 * scale) - origin_x),
        min(size[1], math.ceil(rect.y1 * scale) - origin_y),
    )


def _detect_protected_overlap(image: Image.Image, target: tuple[int, int, int, int]) -> str | None:
    x0, y0, x1, y1 = target
    crop = image.crop(target).convert("RGB")
    raw = crop.tobytes()
    colorful = sum(
        1 for offset in range(0, len(raw), 3)
        if max(raw[offset:offset + 3]) - min(raw[offset:offset + 3]) >= 55 and min(raw[offset:offset + 3]) < 210
    )
    if colorful >= max(4, (len(raw) // 3) // 500):
        return "BACKGROUND_COLORED_OVERLAP"
    gray = ImageOps.grayscale(crop)
    width, height = gray.size
    if width < 2 or height < 2:
        return "BACKGROUND_UNCERTAIN"
    rows = [sum(1 for x in range(width) if gray.getpixel((x, y)) < 105) for y in range(height)]
    columns = [sum(1 for y in range(height) if gray.getpixel((x, y)) < 105) for x in range(width)]
    if any(count >= width * 0.92 for count in rows) or any(count >= height * 0.92 for count in columns):
        return "BACKGROUND_RULE_OVERLAP"
    if _has_oversized_connected_ink(crop):
        return "BACKGROUND_UNCERTAIN"
    return None


def _has_oversized_connected_ink(image: Image.Image) -> bool:
    """Refuse a raster target containing a long connected mark across the word."""
    gray = ImageOps.grayscale(image)
    width, height = gray.size
    if width < 2 or height < 2 or width * height > 200_000:
        return True
    pixels = gray.tobytes()
    visited = bytearray(len(pixels))
    min_width = max(12, math.ceil(width * 0.55))
    min_height = max(5, math.ceil(height * 0.35))
    for start, value in enumerate(pixels):
        if value >= 105 or visited[start]:
            continue
        queue = [start]
        visited[start] = 1
        left = right = start % width
        top = bottom = start // width
        while queue:
            current = queue.pop()
            x, y = current % width, current // width
            left = min(left, x)
            right = max(right, x)
            top = min(top, y)
            bottom = max(bottom, y)
            for neighbor_y in range(max(0, y - 1), min(height, y + 2)):
                row = neighbor_y * width
                for neighbor_x in range(max(0, x - 1), min(width, x + 2)):
                    neighbor = row + neighbor_x
                    if not visited[neighbor] and pixels[neighbor] < 105:
                        visited[neighbor] = 1
                        queue.append(neighbor)
        if right - left + 1 >= min_width and bottom - top + 1 >= min_height:
            return True
    return False


def _repair_ink_mask(image: Image.Image, target: tuple[int, int, int, int]) -> tuple[Image.Image, Image.Image]:
    rgb = image.convert("RGB")
    x0, y0, x1, y1 = target
    gray = ImageOps.grayscale(rgb)
    perimeter: list[int] = []
    for x in range(x0, x1):
        perimeter.extend((gray.getpixel((x, max(0, y0 - 1))), gray.getpixel((x, min(rgb.height - 1, y1)))))
    for y in range(y0, y1):
        perimeter.extend((gray.getpixel((max(0, x0 - 1), y)), gray.getpixel((min(rgb.width - 1, x1), y))))
    if not perimeter:
        raise ValueError("empty local background sample")
    background = median(perimeter)
    if background < 120:
        raise ValueError("background is too dark or uncertain")
    threshold = max(72, int(background) - 32)
    box_mask = Image.new("L", rgb.size, 0)
    ImageDraw.Draw(box_mask).rectangle((x0, y0, x1 - 1, y1 - 1), fill=255)
    dark = Image.eval(gray, lambda value: 255 if value < threshold else 0)
    ink_mask = ImageChops.multiply(dark.filter(ImageFilter.MaxFilter(3)), box_mask)
    # A mask touching the box edge can mean the OCR geometry clips source ink.
    if any(ink_mask.getpixel((x, y)) for x in range(x0, x1) for y in (y0, y1 - 1)):
        raise ValueError("source ink touches the target edge")
    if any(ink_mask.getpixel((x, y)) for y in range(y0, y1) for x in (x0, x1 - 1)):
        raise ValueError("source ink touches the target edge")

    repaired = rgb.copy()
    source, destination, mask = rgb.load(), repaired.load(), ink_mask.load()
    for y in range(y0, y1):
        x = x0
        while x < x1:
            if not mask[x, y]:
                x += 1
                continue
            run_start = x
            while x < x1 and mask[x, y]:
                x += 1
            run_end = x - 1
            left_x = run_start - 1 if run_start > 0 else None
            right_x = x if x < rgb.width else None
            while left_x is not None and mask[left_x, y]:
                left_x -= 1
                if left_x < 0:
                    left_x = None
            while right_x is not None and mask[right_x, y]:
                right_x += 1
                if right_x >= rgb.width:
                    right_x = None
            if left_x is None and right_x is None:
                raise ValueError("no local scanline samples surround selected ink")
            left = source[left_x, y] if left_x is not None else None
            right = source[right_x, y] if right_x is not None else None
            span = max(1, run_end - run_start + 2)
            for pixel_x in range(run_start, run_end + 1):
                if left is not None and right is not None:
                    fraction = (pixel_x - run_start + 1) / span
                    destination[pixel_x, y] = tuple(round(left[c] * (1 - fraction) + right[c] * fraction) for c in range(3))
                else:
                    destination[pixel_x, y] = left if left is not None else right
    return repaired, ink_mask


def _ink_color(image: Image.Image, mask: Image.Image) -> tuple[float, float, float]:
    pixels = image.convert("RGB").load()
    selected = [pixels[x, y] for y in range(image.height) for x in range(image.width) if mask.getpixel((x, y))]
    if not selected:
        return (0.0, 0.0, 0.0)
    selected.sort(key=lambda pixel: sum(pixel) / 3)
    darkest = selected[:max(1, round(len(selected) * 0.2))]
    return tuple(median([pixel[channel] for pixel in darkest]) / 255 for channel in range(3))


def _png_bytes(image: Image.Image) -> bytes:
    stream = BytesIO()
    image.save(stream, format="PNG", optimize=False)
    return stream.getvalue()


def _page_geometry(page: fitz.Page) -> dict[str, Any]:
    return {
        "rect": tuple(page.rect),
        "cropbox": tuple(page.cropbox),
        "mediabox": tuple(page.mediabox),
        "rotation": page.rotation,
    }


def _word_records(page: fitz.Page) -> list[tuple[str, tuple[float, float, float, float]]]:
    return [(str(word[4]), tuple(round(float(value), 2) for value in word[:4])) for word in page.get_text("words")]


def _image_hashes(document: fitz.Document) -> set[str]:
    hashes: set[str] = set()
    for page in document:
        for image in page.get_images(full=True):
            xref = int(image[0])
            if xref > 0:
                hashes.add(sha256(document.extract_image(xref)["image"]).hexdigest())
    return hashes


def _render(page: fitz.Page, dpi: int) -> Image.Image:
    pix = page.get_pixmap(dpi=dpi, colorspace=fitz.csRGB, alpha=False)
    return Image.frombytes("RGB", (pix.width, pix.height), pix.samples)


def _pixel_counts(before: Image.Image, after: Image.Image, allowed: list[fitz.Rect], dpi: int) -> tuple[int, int]:
    if before.size != after.size:
        return -1, -1
    difference = ImageChops.difference(before, after)
    maximum = ImageChops.lighter(ImageChops.lighter(*difference.split()[:2]), difference.split()[2])
    changed = maximum.point(lambda value: 255 if value > 2 else 0)
    mask = Image.new("L", before.size, 0)
    draw = ImageDraw.Draw(mask)
    # The safety band includes a further raster antialiasing pixel at each DPI.
    dpi_scale = dpi / 72.0
    for rect in allowed:
        x0 = max(0, math.floor(rect.x0 * dpi_scale) - 1)
        y0 = max(0, math.floor(rect.y0 * dpi_scale) - 1)
        x1 = min(before.width, math.ceil(rect.x1 * dpi_scale) + 1)
        y1 = min(before.height, math.ceil(rect.y1 * dpi_scale) + 1)
        if x1 > x0 and y1 > y0:
            draw.rectangle((x0, y0, x1 - 1, y1 - 1), fill=255)
    outside = ImageChops.multiply(changed, ImageChops.invert(mask))
    return changed.histogram()[255], outside.histogram()[255]


def _validate_candidate(source_path: Path, candidate_path: Path, plans: list[dict[str, Any]], page_count: int,
                        geometry: list[dict[str, Any]], original_words: list[list[tuple[str, tuple[float, float, float, float]]]],
                        image_hashes: set[str], cancellation_check: Callable[[], None] | None) -> dict[str, Any]:
    checks: dict[str, Any] = {"valid": False, "target_results": []}
    outside_by_dpi = {str(dpi): 0 for dpi in _VALIDATION_DPIS}
    with fitz.open(source_path) as source, fitz.open(candidate_path) as candidate:
        checks["page_count"] = len(candidate) == page_count == len(source)
        checks["geometry"] = all(_page_geometry(candidate[index]) == geometry[index] for index in range(page_count))
        checks["image_streams_preserved"] = image_hashes.issubset(_image_hashes(candidate))
        target_page_indices = {plan["page_index"] for plan in plans}
        for dpi in _VALIDATION_DPIS:
            if cancellation_check:
                cancellation_check()
            for page_index in range(page_count):
                original_image, candidate_image = _render(source[page_index], dpi), _render(candidate[page_index], dpi)
                allowed = []
                for plan in plans:
                    if plan["page_index"] != page_index:
                        continue
                    visible_rect = fitz.Rect(plan["allowed_rect"]) * source[page_index].rotation_matrix
                    visible_rect.normalize()
                    allowed.append(visible_rect)
                changed, outside = _pixel_counts(original_image, candidate_image, allowed, dpi)
                outside_by_dpi[str(dpi)] += max(0, outside)
                if page_index not in target_page_indices and changed != 0:
                    checks[f"unedited_page_{page_index + 1}_{dpi}_identical"] = False
                elif page_index not in target_page_indices:
                    checks[f"unedited_page_{page_index + 1}_{dpi}_identical"] = True
        checks["outside_changed_pixels_by_dpi"] = outside_by_dpi
        checks["outside_changed_pixels_144dpi"] = outside_by_dpi["144"]
        checks["target_results"] = []
        target_content_valid = True
        text_order_preserved = True
        plans_by_page: dict[int, list[dict[str, Any]]] = {}
        for plan in plans:
            plans_by_page.setdefault(plan["page_index"], []).append(plan)
        for page_index in range(page_count):
            if cancellation_check:
                cancellation_check()
            expected_words = _expected_page_words(source[page_index], plans_by_page.get(page_index, []))
            candidate_words = [str(word[4]) for word in candidate[page_index].get_text("words", sort=False)]
            text_order_preserved &= candidate_words == expected_words
        checks["text_reading_order_preserved"] = text_order_preserved
        for plan in plans:
            page_index = plan["page_index"]
            page = candidate[page_index]
            rect = plan["target_rect"]
            replacement = plan["edit"]["replacement_text"]
            replacement_tokens = replacement.split()
            replacement_tokens = replacement.split()
            target_words = [
                word for word in page.get_text("words", sort=False)
                if fitz.Rect(word[:4]).intersects(rect)
            ]
            old_hits = [
                word for word in target_words
                if _normalize_text(str(word[4])) == _normalize_text(plan["edit"]["expected_original_text"])
            ]
            replacement_hits = [
                str(word[4]) for word in page.get_text("words", sort=False)
                if str(word[4]) in replacement_tokens
                and fitz.Rect(word[:4]).intersects(plan["replacement_rect"])
            ]
            if replacement:
                allowed_rect = plan["allowed_rect"]
                exact_search = any(found.intersects(allowed_rect) for found in page.search_for(replacement))
            else:
                exact_search = True
            checks["target_results"].append({
                "page_num": page_index + 1,
                "element_id": plan["edit"]["element_id"],
                "word_id": plan["edit"]["word_id"],
                "representation": plan["representation"],
                "replacement_searchable": exact_search,
                "replacement_hits_at_target": replacement_hits,
                "old_target_hits_at_target": len(old_hits),
            })
            target_content_valid &= (
                len(old_hits) == 0
                and replacement_hits == replacement_tokens
                and exact_search
            )

        neighbors_preserved = True
        for page_index in range(page_count):
            if cancellation_check:
                cancellation_check()
            allowed = [plan["allowed_rect"] for plan in plans if plan["page_index"] == page_index]
            source_neighbors = Counter(
                record for record in original_words[page_index]
                if not any(fitz.Rect(record[1]).intersects(rect) for rect in allowed)
            )
            candidate_neighbors = Counter(
                record for record in _word_records(candidate[page_index])
                if not any(fitz.Rect(record[1]).intersects(rect) for rect in allowed)
            )
            neighbors_preserved &= source_neighbors == candidate_neighbors
        checks["neighbors_preserved"] = neighbors_preserved
        checks["outside_pixels_clear"] = all(value == 0 for value in outside_by_dpi.values())
        checks["target_content_valid"] = target_content_valid
        checks["valid"] = all((checks["page_count"], checks["geometry"], checks["image_streams_preserved"],
                               checks["neighbors_preserved"], checks["outside_pixels_clear"], checks["target_content_valid"],
                               checks["text_reading_order_preserved"]))
    return checks


def _expected_page_words(page: fitz.Page, plans: list[dict[str, Any]]) -> list[str]:
    source_words = page.get_text("words", sort=False)
    replacement_by_index = {
        plan["source_word_index"]: plan["edit"]["replacement_text"].split()
        for plan in plans
        if plan["source_word_index"] is not None
    }
    insertions_by_slot: dict[int, list[dict[str, Any]]] = {}
    for plan in plans:
        if plan["source_word_index"] is None:
            insertions_by_slot.setdefault(plan["insertion_slot"], []).append(plan)
    expected: list[str] = []
    for slot in range(len(source_words) + 1):
        for plan in sorted(insertions_by_slot.get(slot, []), key=lambda item: item["edit_order"]):
            expected.extend(plan["edit"]["replacement_text"].split())
        if slot < len(source_words):
            if slot in replacement_by_index:
                expected.extend(replacement_by_index[slot])
            else:
                expected.append(str(source_words[slot][4]))
    return expected


def _sha256_file(path: Path) -> str:
    digest = sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _refusal(error_code: str, **details: Any) -> dict[str, Any]:
    return {"status": "REFUSED", "error_code": error_code, **details}


def isolated_compile_scanned_word_edits(
    input_path: str | Path,
    output_pdf_path: str | Path,
    envelope: dict[str, Any],
    resolved_targets: list[dict[str, Any]],
    expected_source_sha256: str,
    cancellation_check: Callable[[], None] | None = None,
) -> dict[str, Any]:
    """Fixed native-operation entry point with a private refusal sentinel.

    The isolation wrapper requires a declared output file. A refusal marker is
    copied only to the actor's private temp path and is never uploaded or
    returned by a successful job.
    """
    result = compile_scanned_word_edits(
        input_path,
        output_pdf_path,
        envelope,
        resolved_targets,
        expected_source_sha256,
        cancellation_check,
    )
    if result.get("status") != "EDITED":
        sentinel = fitz.open()
        sentinel.new_page(width=72, height=72)
        output = Path(output_pdf_path)
        output.parent.mkdir(parents=True, exist_ok=True)
        sentinel.save(output)
        sentinel.close()
    return result
